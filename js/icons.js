const _iconCache = {};
function iconURL(name){
  if (_iconCache[name]) return _iconCache[name];
  const rows = ICONS[name], h = rows.length, w = Math.max(...rows.map(r=>r.length));
  const c = document.createElement('canvas'); c.width = w; c.height = h; const g = c.getContext('2d');
  rows.forEach((r,y)=>[...r].forEach((ch,x)=>{ if(ICON_PAL[ch]){ g.fillStyle = ICON_PAL[ch]; g.fillRect(x,y,1,1);} }));
  return (_iconCache[name] = c.toDataURL());
}
function icon(name, extra=''){ const n = ICONS[name].length; return `<img class="ic ${n<=8?'ic-s':'ic-m'} ${extra}" src="${iconURL(name)}" alt="">`; }
